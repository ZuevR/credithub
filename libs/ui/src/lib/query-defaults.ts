/**
 * Настройки запросов по умолчанию - одни на хост и на remote.
 *
 * Отдаём обычный объект опций, а не готовый `QueryClient`: библиотека не должна
 * тянуть рантайм-зависимость от react-query (её не используют ни Angular, ни
 * core-api), а `QueryClient` из этих опций создаёт каждая сторона сама.
 *
 * Значения обязаны совпадать у shell (hosted-режим) и `mfe-credits`
 * (standalone): иначе одно приложение ведёт себя по-разному в зависимости от
 * способа запуска, и это выглядит как невоспроизводимый баг.
 */
export const queryDefaults = {
  queries: {
    // Данные портфеля меняются редко, а окно дедупликации защищает от
    // повторного похода в BFF при каждом монтировании и возврате на вкладку.
    staleTime: 30_000,
    refetchOnWindowFocus: false,
    // Одна попытка: если BFF недоступен, пользователю полезнее увидеть ошибку
    // и кнопку «Повторить», чем ждать серию автоматических ретраев.
    retry: 1,
  },
} as const;
